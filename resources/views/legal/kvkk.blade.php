<h4>1. Veri Sorumlusu</h4>
<p>6698 sayılı Kişisel Verilerin Korunması Kanunu ("KVKK") uyarınca, kişisel verileriniz veri sorumlusu sıfatıyla {{ setting('havale_hesap_adi', setting('site_adi')) }} tarafından aşağıda açıklanan kapsamda işlenmektedir.</p>

<h4>2. İşlenen Kişisel Veriler</h4>
<p>Ad-soyad, iletişim bilgileri (telefon, e-posta, adres), sipariş ve ödeme bilgileri, randevu bilgileri ve site kullanımına ilişkin teknik veriler işlenebilmektedir.</p>

<h4>3. İşleme Amaçları</h4>
<ul>
    <li>Siparişlerin alınması, hazırlanması ve teslimi,</li>
    <li>Müşteri ilişkileri ve destek hizmetlerinin yürütülmesi,</li>
    <li>Yasal yükümlülüklerin (fatura, muhasebe vb.) yerine getirilmesi,</li>
    <li>Randevu taleplerinin değerlendirilmesi.</li>
</ul>

<h4>4. Aktarım</h4>
<p>Kişisel verileriniz; kargo firmaları, ödeme kuruluşları ve yasal olarak yetkili kamu kurumları ile sınırlı olarak ve amaçla bağlantılı şekilde paylaşılabilir.</p>

<h4>5. Haklarınız</h4>
<p>KVKK'nın 11. maddesi kapsamında; verilerinizin işlenip işlenmediğini öğrenme, düzeltilmesini veya silinmesini isteme ve diğer haklarınızı {{ setting('eposta') }} adresine başvurarak kullanabilirsiniz.</p>
