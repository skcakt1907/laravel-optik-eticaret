<h4>Teslimat</h4>
<ul>
    <li>Siparişleriniz, ödemenin onaylanmasının ardından anlaşmalı kargo firması ile adresinize gönderilir.</li>
    <li>Kargo ücreti ödeme sayfasında belirtilir. {{ money(setting('kargo_bedava_limit', 0)) }} ve üzeri alışverişlerde kargo ücretsizdir.</li>
    <li>Havale/EFT ile ödemelerde, ödeme hesabımıza geçtikten sonra sipariş hazırlanmaya başlanır.</li>
</ul>

<h4>İade ve Cayma Hakkı</h4>
<ul>
    <li>Ürünü teslim aldığınız tarihten itibaren <strong>14 gün</strong> içinde cayma hakkınızı kullanabilirsiniz.</li>
    <li>İade edilecek ürünün kullanılmamış, denenmemiş ve orijinal ambalajının zarar görmemiş olması gerekir.</li>
    <li>İade talebinizi {{ setting('eposta') }} adresine veya {{ setting('telefon') }} numarasına iletebilirsiniz.</li>
    <li>İadesi onaylanan ürün bedeli, ürün tarafımıza ulaştıktan sonra ödeme yönteminize uygun şekilde 14 gün içinde iade edilir.</li>
</ul>

<h4>İade Edilemeyen Ürünler</h4>
<ul>
    <li>Kişiye özel üretilen dereceli/numaralı gözlük camları,</li>
    <li>Hijyenik nedenlerle ambalajı açılmış kontakt lensler,</li>
    <li>Kullanılmış veya hasar görmüş ürünler.</li>
</ul>

<h4>Hasarlı / Yanlış Ürün</h4>
<p>Kargo teslimatı sırasında pakette hasar fark ederseniz tutanak tutturmanız önerilir. Yanlış veya hasarlı ürün teslim alınması durumunda kargo ve değişim masrafları tarafımıza aittir.</p>
