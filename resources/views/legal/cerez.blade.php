<h4>Çerez Politikası</h4>
<p>İnternet sitemiz, deneyiminizi iyileştirmek için çerezler (cookies) kullanır. Bu politika hangi çerezleri ne amaçla kullandığımızı açıklar.</p>

<h4>Çerez Nedir?</h4>
<p>Çerezler, ziyaret ettiğiniz internet siteleri tarafından tarayıcınıza kaydedilen küçük metin dosyalarıdır.</p>

<h4>Kullandığımız Çerezler</h4>
<ul>
    <li><strong>Zorunlu çerezler:</strong> Oturum, sepet ve güvenlik gibi temel işlevler için gereklidir.</li>
    <li><strong>İşlevsel çerezler:</strong> Tercihlerinizi hatırlamak için kullanılır.</li>
    <li><strong>Analitik çerezler:</strong> Site kullanımını anlamak ve geliştirmek için (etkinleştirilmişse) kullanılır.</li>
</ul>

<h4>Çerezlerin Yönetimi</h4>
<p>Tarayıcınızın ayarlarından çerezleri silebilir veya engelleyebilirsiniz. Zorunlu çerezlerin engellenmesi durumunda sitenin bazı bölümleri düzgün çalışmayabilir.</p>
